  @override
  Future<MyResult<ListingDetailDomainModel>> getListing(String id) async {
    await Future<void>.delayed(const Duration(milliseconds: 280));
    final mapped = _byId[id] ?? _byId['1']!;
    // Preserve requested id on fallback so navigation stays consistent.
    if (_byId.containsKey(id)) {
      return MyResult.isSuccess(mapped);
    }
    return MyResult.isSuccess(
      ListingDetailDomainModel(
        id: id,
        title: mapped.title,
        shopName: mapped.shopName,
        ownerUserId: mapped.ownerUserId,
        ownerVerified: mapped.ownerVerified,
        categoryName: mapped.categoryName,
        dealType: mapped.dealType,
