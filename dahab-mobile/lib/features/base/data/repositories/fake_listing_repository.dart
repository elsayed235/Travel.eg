        city: mapped.city,
        deliveryLabel: mapped.deliveryLabel,
        rentPrice: mapped.rentPrice,
        rentUnit: mapped.rentUnit,
        buyPrice: mapped.buyPrice,
        buyUnit: mapped.buyUnit,
        month: mapped.month,
        stockAvailable: mapped.stockAvailable,
        stockTotal: mapped.stockTotal,
        availability: mapped.availability,
        terms: mapped.terms,
        moneyCycle: mapped.moneyCycle,
