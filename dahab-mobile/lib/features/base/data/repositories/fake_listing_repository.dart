    final month = DateTime(2026, 10);
    DateTime d(int day) => DateTime(month.year, month.month, day);
    final availability = <DateTime, DayAvailability>{
      for (var day = 1; day <= 31; day++)
        d(day): DayAvailability(available: total, total: total),
    };
    for (final day in [22, 23, 24]) {
      availability[d(day)] = DayAvailability(available: 0, total: total);
    }
    for (final day in [21, 29]) {
      availability[d(day)] = DayAvailability(
        available: (total * 0.4).round(),
        total: total,
      );
    }
    return availability;
  }

