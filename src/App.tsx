import React, { useState, useEffect, lazy, Suspense } from 'react';
import { ThemeProvider, useTheme } from './context/ThemeContext';
import { AppStateProvider, useTrip } from './context';
import { V2Navbar } from './components/navigation/V2Navbar';
import { V2HomeCockpit } from './components/home/V2HomeCockpit';
import { JourneyStage, AppRoute } from './types';
import { LanguageProvider, useLanguage } from './i18n/LanguageContext';
import { DahabTimeProvider } from './context/DahabTimeContext';
import { SinaiFloatingQuickDock } from './components/common/SinaiFloatingQuickDock';
import { StickyBookingBottomBar } from './components/common/StickyBookingBottomBar';
import { ErrorBoundary } from './components/common/ErrorBoundary';
import { RequireRole } from './components/auth/RequireRole';
import { DayGiFloatingButton } from './components/daygi/DayGiFloatingButton';


/**
 * Route views are loaded when their route is reached, not on first paint.
 *
 * The build was one 3,239 kB chunk (794 kB gzipped) containing all 25 views,
 * the maps SDK, the intelligence dataset and the geography dataset — shipped in
 * full to a traveler who only wanted the homepage, on Sinai mobile networks.
 * The api client's own timeout comment names that connectivity as the reason it
 * exists.
 *
 * Written out rather than generated by a helper: each import maps its own named
 * export to a default, which is what lets TypeScript keep the component's real
 * prop types instead of widening them away.
 *
 * Removed at the same time: an eager import of AiDirectorView that nothing
 * rendered — both /daygi and /ai-director resolve to DayGiConciergeView.
 */
const BookNowCommerceModal = lazy(() => import('./components/commerce/BookNowCommerceModal').then(m => ({ default: m.BookNowCommerceModal })));
const BookNowCommerceView = lazy(() => import('./components/commerce/BookNowCommerceView').then(m => ({ default: m.BookNowCommerceView })));
const PlanForMeView = lazy(() => import('./components/home/PlanForMeView').then(m => ({ default: m.PlanForMeView })));
const TripPlanner = lazy(() => import('./components/planner/TripPlanner').then(m => ({ default: m.TripPlanner })));
const MyTripView = lazy(() => import('./components/mytrip/MyTripView').then(m => ({ default: m.MyTripView })));
const ExploreView = lazy(() => import('./components/explore/ExploreView').then(m => ({ default: m.ExploreView })));
const BookingsView = lazy(() => import('./components/bookings/BookingsView').then(m => ({ default: m.BookingsView })));
const DepartureView = lazy(() => import('./components/departure/DepartureView').then(m => ({ default: m.DepartureView })));
const PostTripView = lazy(() => import('./components/posttrip/PostTripView').then(m => ({ default: m.PostTripView })));
const ProfileView = lazy(() => import('./components/profile/ProfileView').then(m => ({ default: m.ProfileView })));
const FoodNowView = lazy(() => import('./components/food/FoodNowView').then(m => ({ default: m.FoodNowView })));
const ChangeAndRecoveryView = lazy(() => import('./components/recovery/ChangeAndRecoveryView').then(m => ({ default: m.ChangeAndRecoveryView })));
const HelpMeNowView = lazy(() => import('./components/help/HelpMeNowView').then(m => ({ default: m.HelpMeNowView })));
const PreArrivalBriefing = lazy(() => import('./components/briefing/PreArrivalBriefing').then(m => ({ default: m.PreArrivalBriefing })));
const EarlyArrivalView = lazy(() => import('./components/arrival/EarlyArrivalView').then(m => ({ default: m.EarlyArrivalView })));
const FirstTwoHoursView = lazy(() => import('./components/arrival/FirstTwoHoursView').then(m => ({ default: m.FirstTwoHoursView })));
const DailyCompanionDay2View = lazy(() => import('./components/companion/DailyCompanionDay2View').then(m => ({ default: m.DailyCompanionDay2View })));
const WhatShouldIDoNowView = lazy(() => import('./components/spontaneous/WhatShouldIDoNowView').then(m => ({ default: m.WhatShouldIDoNowView })));
const DahabLiveView = lazy(() => import('./components/live/DahabLiveView').then(m => ({ default: m.DahabLiveView })));
const DayGiConciergeView = lazy(() => import('./components/daygi/DayGiConciergeView').then(m => ({ default: m.DayGiConciergeView })));
const AuthView = lazy(() => import('./components/auth/AuthView').then(m => ({ default: m.AuthView })));
const AhmedJourneyWalkthrough = lazy(() => import('./components/common/AhmedJourneyWalkthrough').then(m => ({ default: m.AhmedJourneyWalkthrough })));
const OperationsConsoleView = lazy(() => import('./components/operations/command-center/CommandCenterShell').then(m => ({ default: m.CommandCenterShell })));
const SupplierPortalView = lazy(() => import('./components/supplier/SupplierPortalView').then(m => ({ default: m.SupplierPortalView })));
const MarketIntelligenceView = lazy(() => import('./components/intelligence/MarketIntelligenceView').then(m => ({ default: m.MarketIntelligenceView })));
const ProgramDetailView = lazy(() => import('./components/programs/ProgramDetailView').then(m => ({ default: m.ProgramDetailView })));
const ExperienceDetailView = lazy(() => import('./components/experiences/ExperienceDetailView').then(m => ({ default: m.ExperienceDetailView })));
const SearchDrawer = lazy(() => import('./components/common/SearchDrawer').then(m => ({ default: m.SearchDrawer })));

/**
 * Shown while a route's chunk is being fetched.
 *
 * Deliberately a live region: on a slow connection the gap between tapping a
 * route and its code arriving is real, and a screen reader user is otherwise
 * told nothing at all.
 */
const RouteLoading: React.FC = () => (
  <div
    role="status"
    aria-live="polite"
    className="min-h-[60vh] flex flex-col items-center justify-center gap-3"
  >
    <span
      aria-hidden="true"
      className="w-6 h-6 rounded-full border-2 border-[var(--accent-primary)] border-t-transparent animate-spin"
    />
    <span className="text-sm text-[var(--text-secondary)]">Loading…</span>
  </div>
);

function MainAppContent() {
  const { currentRoute, navigateTo, toast, journeyStage } = useTrip();
  const { language } = useLanguage();

  /**
   * Human, localized label for the live region below.
   *
   * It previously announced `Current route: /home, Journey stage: discover` —
   * raw internal identifiers, always in English even in the Arabic UI, to the
   * one audience that depends entirely on that text.
   */
  const routeAnnouncement = (route: string): string => {
    const labels: Record<string, { en: string; ar: string }> = {
      '/': { en: 'Home', ar: 'الرئيسية' },
      '/home': { en: 'Home', ar: 'الرئيسية' },
      '/discover': { en: 'Home', ar: 'الرئيسية' },
      '/explore': { en: 'Explore Dahab', ar: 'استكشف دهب' },
      '/my-trip': { en: 'My Trip', ar: 'رحلتي' },
      '/bookings': { en: 'My Bookings', ar: 'حجوزاتي' },
      '/quick-book': { en: 'Book Now', ar: 'احجز الآن' },
      '/book-now': { en: 'Book Now', ar: 'احجز الآن' },
      '/plan-for-me': { en: 'Plan It For Me', ar: 'خططها لي' },
      '/trip-builder': { en: 'Trip Planner', ar: 'مخطط الرحلة' },
      '/trip-preview': { en: 'Trip Preview', ar: 'معاينة الرحلة' },
      '/food': { en: 'Food & Dining', ar: 'الأكل والمطاعم' },
      '/help': { en: 'Help & Emergency', ar: 'المساعدة والطوارئ' },
      '/live': { en: 'Dahab Live', ar: 'دهب دلوقتي' },
      '/daygi': { en: 'AI Concierge', ar: 'المرشد الذكي' },
      '/ai-director': { en: 'AI Concierge', ar: 'المرشد الذكي' },
      '/profile': { en: 'Profile', ar: 'الملف الشخصي' },
      '/programs': { en: 'Program Details', ar: 'تفاصيل البرنامج' },
      '/experiences': { en: 'Experience Details', ar: 'تفاصيل التجربة' }
    };
    const label = labels[route];
    if (!label) return '';
    return language === 'ar' ? `تم فتح صفحة ${label.ar}` : `${label.en} page loaded`;
  };

  // Search and Booking Modals state
  const [isSearchOpen, setIsSearchOpen] = useState(false);
  const [isQuickBookOpen, setIsQuickBookOpen] = useState(false);

  // Special sub-view override state (for testing direct journey stages)
  const [specialStageOverride, setSpecialStageOverride] = useState<JourneyStage | null>(null);

  // Accepts null: the walkthrough passes null to clear the override, and
  // specialStageOverride is already `JourneyStage | null`.
  const handleStageSelect = (stage: JourneyStage | null) => {
    setSpecialStageOverride(stage);
  };

  // Scroll to top on route change
  useEffect(() => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }, [currentRoute, specialStageOverride]);

  // Keyboard shortcut for Cmd/Ctrl+K spotlight search.
  // Skip when the Command Center is active — it owns its own palette.
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
        if (currentRoute === '/ops-console') return;
        e.preventDefault();
        setIsSearchOpen((prev) => !prev);
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [currentRoute]);

  // Render view based on stage override or currentRoute
  const renderCurrentView = () => {
    // 1. Direct Stage Overrides for testing all 12 stages
    if (specialStageOverride === 'prepare') {
      return (
        <PreArrivalBriefing
          onBackToMyTrip={() => {
            setSpecialStageOverride(null);
            navigateTo('/my-trip');
          }}
          onReadyConfirmed={() => {
            setSpecialStageOverride('arrive');
            navigateTo('/my-trip');
          }}
          onOpenHelp={() => navigateTo('/help')}
        />
      );
    }

    if (specialStageOverride === 'arrive') {
      return (
        <EarlyArrivalView
          onBackToMyTrip={() => {
            setSpecialStageOverride(null);
            navigateTo('/my-trip');
          }}
          onNavigateToFirstTwoHours={() => {
            setSpecialStageOverride(null);
            navigateTo('/first-two-hours');
          }}
          onExploreClick={() => navigateTo('/explore')}
          onOpenHelp={() => navigateTo('/help')}
        />
      );
    }

    if (specialStageOverride === 'experience') {
      return (
        <DailyCompanionDay2View
          onBackToMyTrip={() => {
            setSpecialStageOverride(null);
            navigateTo('/my-trip');
          }}
          onNavigateToChangeRecovery={() => navigateTo('/change-recovery')}
          onNavigateToWhatShouldIDoNow={() => setSpecialStageOverride('spontaneous')}
          onNavigateToFoodNow={() => navigateTo('/food')}
          onExploreClick={() => navigateTo('/explore')}
          onOpenHelp={() => navigateTo('/help')}
        />
      );
    }

    if (specialStageOverride === 'spontaneous') {
      return (
        <WhatShouldIDoNowView
          onBackToMyTrip={() => {
            setSpecialStageOverride(null);
            navigateTo('/my-trip');
          }}
          onBackToCompanion={() => setSpecialStageOverride('experience')}
          onNavigateToFoodNow={() => navigateTo('/food')}
          onExploreClick={() => navigateTo('/explore')}
          onOpenHelp={() => navigateTo('/help')}
        />
      );
    }

    // 2. Primary Route Matching
    switch (currentRoute) {
      case '/explore':
        return <ExploreView />;

      case '/bookings':
        return <BookingsView />;

      case '/quick-book':
      case '/book-now':
        return <BookNowCommerceView />;

      case '/departure':
        return <DepartureView />;

      case '/post-trip':
      case '/memories':
        return <PostTripView />;

      case '/profile':
        return <ProfileView />;

      case '/food':
        return (
          <FoodNowView
            onBackToMyTrip={() => {
              setSpecialStageOverride(null);
              navigateTo('/my-trip');
            }}
            onBackToCompanion={() => {
              setSpecialStageOverride('experience');
              navigateTo('/my-trip');
            }}
            onExploreClick={() => navigateTo('/explore')}
            onOpenHelp={() => navigateTo('/help')}
          />
        );

      case '/change-recovery':
        return (
          <ChangeAndRecoveryView
            onBackToMyTrip={() => {
              setSpecialStageOverride(null);
              navigateTo('/my-trip');
            }}
            onBackToCompanion={() => {
              setSpecialStageOverride('experience');
              navigateTo('/my-trip');
            }}
            onExploreClick={() => navigateTo('/explore')}
            onOpenHelp={() => navigateTo('/help')}
          />
        );

      case '/help':
        return (
          <HelpMeNowView
            onBackToMyTrip={() => {
              setSpecialStageOverride(null);
              navigateTo('/my-trip');
            }}
            onBackToCompanion={() => {
              setSpecialStageOverride('experience');
              navigateTo('/my-trip');
            }}
            onNavigateToChangeRecovery={() => navigateTo('/change-recovery')}
            onExploreClick={() => navigateTo('/explore')}
          />
        );

      case '/plan-for-me':
        return <PlanForMeView />;

      case '/trip-builder':
      case '/trip-preview':
        return (
          <TripPlanner
            onExitToHome={() => {
              setSpecialStageOverride(null);
              navigateTo('/home');
            }}
          />
        );

      case '/my-trip':
      case '/my-trip/day':
      case '/my-trip/activity':
        return (
          <MyTripView
            onBackToHome={() => {
              setSpecialStageOverride(null);
              navigateTo('/home');
            }}
            onExploreClick={() => navigateTo('/explore')}
            initialHelpMeNowOpen={false}
          />
        );

      case '/live':
        return <DahabLiveView />;

      case '/programs':
        return <ProgramDetailView />;

      case '/experiences':
        return <ExperienceDetailView />;

      case '/daygi':
        return <DayGiConciergeView />;

      case '/ai-director':
        return <DayGiConciergeView />;

      case '/auth/sign-in':
        return <AuthView initialMode="sign-in" />;

      case '/auth/sign-up':
        return <AuthView initialMode="sign-up" />;

      case '/auth/forgot-password':
        return <AuthView initialMode="forgot-password" />;

      case '/auth/verify':
      case '/auth/callback':
        return <AuthView initialMode="sign-in" />;

      // Back-office surfaces. These were previously reachable by any anonymous
      // visitor straight from the navbar; the matching APIs are enforced
      // server-side in server/middleware/apiAccessPolicy.ts.
      case '/ops-console':
        return (
          <RequireRole roles={['Operations', 'Admin']}>
            <OperationsConsoleView />
          </RequireRole>
        );

      case '/supplier-portal':
        return (
          <RequireRole roles={['Supplier', 'Operations', 'Admin']}>
            <SupplierPortalView />
          </RequireRole>
        );

      case '/market-intelligence':
        return (
          <RequireRole roles={['Operations', 'Admin']}>
            <MarketIntelligenceView />
          </RequireRole>
        );

      case '/arrive':
        return (
          <EarlyArrivalView
            onBackToMyTrip={() => {
              setSpecialStageOverride(null);
              navigateTo('/my-trip');
            }}
            onNavigateToFirstTwoHours={() => {
              setSpecialStageOverride(null);
              navigateTo('/first-two-hours');
            }}
            onExploreClick={() => navigateTo('/explore')}
            onOpenHelp={() => navigateTo('/help')}
          />
        );

      case '/first-two-hours':
        return (
          <FirstTwoHoursView
            onBackToEarlyArrival={() => {
              setSpecialStageOverride('arrive');
              navigateTo('/arrive');
            }}
            onBackToMyTrip={() => {
              setSpecialStageOverride(null);
              navigateTo('/my-trip');
            }}
            onExploreClick={() => navigateTo('/explore')}
            onOpenHelp={() => navigateTo('/help')}
          />
        );

      case '/discover':
      case '/home':
      default:
        return (
          <V2HomeCockpit
            onOpenQuickBook={() => navigateTo('/quick-book')}
          />
        );
    }
  };

  return (
    <div className="min-h-screen bg-[var(--bg-canvas)] text-[var(--text-primary)] flex flex-col font-['Plus_Jakarta_Sans',sans-serif] relative antialiased selection:bg-[#20A89A]/30 selection:text-[#52C4B7]">
      
      {/* 1. Global Floating OS Navbar */}
      <V2Navbar
        onOpenSearch={() => setIsSearchOpen(true)}
        onOpenQuickBook={() => navigateTo('/quick-book')}
      />

      {/* 2. Main Viewport Content */}
      <main
        id="main-app-content"
        tabIndex={-1}
        role="main"
        aria-label="Dahab Sinai Travel Platform"
        className={`flex-1 w-full focus:outline-none relative z-10 ${
          currentRoute === '/home' || currentRoute === '/discover' || currentRoute === '/'
            ? 'pt-0'
            : 'pt-16 sm:pt-20'
        }`}
      >
        {/* Scoped so one failing view does not take the navbar and global
            actions down with it. Recovers automatically on navigation. */}
        <ErrorBoundary label={`view:${currentRoute}`} resetKeys={[currentRoute, specialStageOverride]}>
          <Suspense fallback={<RouteLoading />}>{renderCurrentView()}</Suspense>
        </ErrorBoundary>
      </main>

      {/* 3. Global Spotlight Search Modal (Cmd+K) */}
      {/* Only fetched once the traveler actually opens it. */}
      {isSearchOpen && (
        <Suspense fallback={null}>
          <SearchDrawer isOpen={isSearchOpen} onClose={() => setIsSearchOpen(false)} />
        </Suspense>
      )}

      {/* 5. ARIA Live Region for Screen Reader Announcements */}
      <div
        aria-live="polite"
        aria-atomic="true"
        className="sr-only"
        id="accessible-live-region"
      >
        {toast || routeAnnouncement(currentRoute)}
      </div>

      {/* 6. High-Contrast Toast Notification */}
      {toast && (
        <div
          role="status"
          aria-label="Notification"
          className="fixed bottom-20 md:bottom-6 right-6 z-50 bg-[var(--surface-card)] text-[var(--text-primary)] px-5 py-3.5 rounded-2xl shadow-2xl border border-[var(--border-subtle)] text-xs font-semibold animate-in fade-in slide-in-from-bottom-3 duration-200 max-w-md flex items-center gap-3 backdrop-blur-xl"
        >
          <span className="w-2.5 h-2.5 rounded-full bg-[#20A89A] animate-pulse flex-shrink-0" aria-hidden="true" />
          <span className="font-medium">{toast}</span>
        </div>
      )}

      {/* 7. Ahmed's 18-Stage Interactive Journey Simulator Pill & Drawer */}
      <Suspense fallback={null}>
        <AhmedJourneyWalkthrough onSelectStageOverride={handleStageSelect} />
      </Suspense>

      {/* 8. Sticky Nav/Booking Bar (Glassmorphism floating bottom bar) */}
      <StickyBookingBottomBar
        onStartCustomPlanner={() => navigateTo('/trip-builder')}
        onOpenItinerary={() => navigateTo('/trip-preview')}
      />

      {/* 9. Sinai Global Rapid Quick-Action Dock (Emergency & Offline Pass) */}
      <SinaiFloatingQuickDock />

      {/* 10. DayGI — reachable everywhere, owning none of the navbar. */}
      <DayGiFloatingButton />
    </div>
  );
}

export default function App() {
  return (
    // Outermost net: catches failures in the providers themselves, which the
    // inner per-view boundary sits below and therefore cannot see.
    <ErrorBoundary label="app-root">
      <ThemeProvider>
        <LanguageProvider>
          <AppStateProvider>
            <DahabTimeProvider>
              <MainAppContent />
            </DahabTimeProvider>
          </AppStateProvider>
        </LanguageProvider>
      </ThemeProvider>
    </ErrorBoundary>
  );
}
